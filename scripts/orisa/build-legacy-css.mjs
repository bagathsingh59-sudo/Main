#!/usr/bin/env node
/**
 * Builds src/styles/orisa/legacy.css — the template CSS needed by the
 * components in src/components/orisa/legacy (ported with port-section.py).
 *
 *   node scripts/orisa/build-legacy-css.mjs
 *
 * 1. PurgeCSS keeps only the rules of the template's Bootstrap, spacing
 *    and main stylesheets whose class names appear in those components.
 * 2. Every selector is prefixed with `.o-legacy`, so the template's
 *    Bootstrap utilities can never leak into Tailwind-styled pages.
 * 3. The template's own colour tokens, dark-mode block, font imports and
 *    icon fonts are dropped — this project's `.orisa` tokens apply.
 * 4. Images referenced from CSS are copied to public/orisa/tpl.
 *
 * Re-run after porting a new section.
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import { PurgeCSS } from "purgecss";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const TEMPLATE =
  process.env.ORISA_TEMPLATE ??
  "/Users/thakurankushsingh/Downloads/orisahtml-410/orisahtml-410/Orisa_v4.1.0_Unzip-First/1.Orisa_HTML_template";
const CSS = ["assets/css/vendors/bootstrap.min.css", "assets/css/vendors/spacing.css", "assets/css/main.css"].map((f) => join(TEMPLATE, f));
const CONTENT_DIR = join(ROOT, "src/components/orisa/legacy");
const OUT = join(ROOT, "src/styles/orisa/legacy.css");
const SCOPE = ".o-legacy";

const content = readdirSync(CONTENT_DIR).filter((f) => f.endsWith(".tsx")).map((f) => join(CONTENT_DIR, f));

const purged = await new PurgeCSS().purge({
  content,
  css: CSS,
  fontFace: true,
  keyframes: true,
  variables: false,
  // Classes added at runtime by the behaviours in useLegacyBehaviors.
  safelist: { standard: ["show", "collapsing", "collapsed", "active", "is-active", "is-changing", "is-open"], greedy: [/^split-/] },
  defaultExtractor: (text) => text.match(/[A-Za-z0-9_:/.-]+/g) ?? [],
});

const scope = postcss.plugin
  ? null
  : null; // (postcss 8: plugins are plain objects)

const plugin = {
  postcssPlugin: "orisa-legacy-scope",
  Once(root) {
    root.walkAtRules((at) => {
      if (at.name === "import" || at.name === "charset" || at.name === "font-face") at.remove();
    });
    root.walkRules((rule) => {
      const parent = rule.parent;
      if (parent?.type === "atrule" && /keyframes$/.test(parent.name)) return;
      if (/\[data-bs-theme/.test(rule.selector)) return rule.remove();

      const isRoot = rule.selectors.every((s) => /^(:root|html|body)\b/.test(s.trim()));
      if (isRoot) {
        // Keep Bootstrap's own variables, never the template's colour / font tokens.
        rule.walkDecls((d) => {
          if (/^--at-/.test(d.prop) || /^(font-family|font-size|line-height|color|background(-color)?|margin|overflow(-x)?)$/.test(d.prop)) d.remove();
        });
        if (!rule.nodes.length) return rule.remove();
      }
      rule.selectors = rule.selectors.map((s) => {
        s = s.trim();
        if (/^(:root|html|body)\b/.test(s)) return s.replace(/^(:root|html|body)\b/, SCOPE);
        return `${SCOPE} ${s}`;
      });
    });
    root.walkDecls((d) => {
      d.value = d.value.replace(/url\((['"]?)\.\.\/(imgs\/[^'")]+)\1\)/g, (_, __, rel) => {
        const src = join(TEMPLATE, "assets", rel);
        const dest = join(ROOT, "public/orisa/tpl", rel.replace(/^imgs\//, ""));
        if (existsSync(src) && !existsSync(dest)) {
          mkdirSync(dirname(dest), { recursive: true });
          copyFileSync(src, dest);
        }
        return `url('/orisa/tpl/${rel.replace(/^imgs\//, "")}')`;
      });
      // Icon fonts are not shipped.
      if (/url\((['"]?)\.\.\/fonts\//.test(d.value)) d.remove();
    });
    // Drop at-rules emptied by the steps above.
    root.walkAtRules((at) => {
      if (at.nodes && at.nodes.length === 0) at.remove();
    });
  },
};
void scope;

let css = "";
for (const part of purged) css += (await postcss([plugin]).process(part.css, { from: undefined })).css + "\n";

const banner = `/* GENERATED by scripts/orisa/build-legacy-css.mjs — do not edit by hand.\n   Template CSS for src/components/orisa/legacy, scoped to ${SCOPE}. */\n`;
writeFileSync(OUT, banner + css);
console.log(`legacy.css: ${(css.length / 1024).toFixed(1)} KB from ${content.length} component(s)`);
